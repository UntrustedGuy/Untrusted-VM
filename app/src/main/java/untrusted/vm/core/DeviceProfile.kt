package untrusted.vm.core

import org.json.JSONObject
import java.io.File
import java.util.Random

/**
 * Manages device identity spoofing per VM instance.
 * Replicates VMOS Pro's device simulation (model, manufacturer, IMEI, MAC, SIM info).
 */
data class DeviceProfile(
    val manufacturer: String = "Google",
    val brand: String = "google",
    val model: String = "Pixel 8 Pro",
    val device: String = "husky",
    val product: String = "husky",
    val board: String = "husky",
    val hardware: String = "zuma",
    val serialNumber: String = generateRandomSerial(),
    val imei: String = generateRandomImei(),
    val androidId: String = generateRandomHex(16),
    val macAddress: String = generateRandomMac(),
    val carrierName: String = "Google Fi",
    val mccMnc: String = "310260"
) {
    companion object {
        fun generateRandomSerial(): String = "UV" + generateRandomHex(10).uppercase()

        fun generateRandomHex(length: Int): String {
            val hexChars = "0123456789abcdef"
            val rand = Random()
            val sb = StringBuilder(length)
            for (i in 0 until length) {
                sb.append(hexChars[rand.nextInt(hexChars.length)])
            }
            return sb.toString()
        }

        fun generateRandomImei(): String {
            val rand = Random()
            val sb = StringBuilder("86")
            for (i in 0 until 12) {
                sb.append(rand.nextInt(10))
            }
            // Luhn checksum digit
            sb.append(rand.nextInt(10))
            return sb.toString()
        }

        fun generateRandomMac(): String {
            val rand = Random()
            val bytes = ByteArray(6)
            rand.nextBytes(bytes)
            bytes[0] = (bytes[0].toInt() and 0xFE or 0x02).toByte() // Locally administered, unicast
            return bytes.joinToString(":") { "%02x".format(it) }
        }

        val PRESET_PIXEL_8 = DeviceProfile(
            manufacturer = "Google",
            brand = "google",
            model = "Pixel 8 Pro",
            device = "husky",
            product = "husky",
            board = "husky",
            hardware = "zuma"
        )

        val PRESET_SAMSUNG_S24 = DeviceProfile(
            manufacturer = "samsung",
            brand = "samsung",
            model = "SM-S928B",
            device = "e3q",
            product = "e3qxeea",
            board = "s5e9945",
            hardware = "samsungexynos9945"
        )

        val PRESET_XIAOMI_14 = DeviceProfile(
            manufacturer = "Xiaomi",
            brand = "Xiaomi",
            model = "23127PN0CC",
            device = "houji",
            product = "houji",
            board = "houji",
            hardware = "qcom"
        )

        fun fromJson(jsonStr: String): DeviceProfile {
            return try {
                val obj = JSONObject(jsonStr)
                DeviceProfile(
                    manufacturer = obj.optString("manufacturer", "Google"),
                    brand = obj.optString("brand", "google"),
                    model = obj.optString("model", "Pixel 8 Pro"),
                    device = obj.optString("device", "husky"),
                    product = obj.optString("product", "husky"),
                    board = obj.optString("board", "husky"),
                    hardware = obj.optString("hardware", "zuma"),
                    serialNumber = obj.optString("serialNumber", generateRandomSerial()),
                    imei = obj.optString("imei", generateRandomImei()),
                    androidId = obj.optString("androidId", generateRandomHex(16)),
                    macAddress = obj.optString("macAddress", generateRandomMac()),
                    carrierName = obj.optString("carrierName", "Google Fi"),
                    mccMnc = obj.optString("mccMnc", "310260")
                )
            } catch (e: Exception) {
                PRESET_PIXEL_8
            }
        }
    }

    fun toJson(): String {
        val obj = JSONObject()
        obj.put("manufacturer", manufacturer)
        obj.put("brand", brand)
        obj.put("model", model)
        obj.put("device", device)
        obj.put("product", product)
        obj.put("board", board)
        obj.put("hardware", hardware)
        obj.put("serialNumber", serialNumber)
        obj.put("imei", imei)
        obj.put("androidId", androidId)
        obj.put("macAddress", macAddress)
        obj.put("carrierName", carrierName)
        obj.put("mccMnc", mccMnc)
        return obj.toString(2)
    }

    /**
     * Writes device profile values to the guest /system/build.prop
     */
    fun applyToBuildProp(buildPropFile: File, androidVersion: String, isRoot: Boolean) {
        val content = StringBuilder()
        content.append("# Generated by Untrusted VM Device Profile\n")
        content.append("ro.product.manufacturer=").append(manufacturer).append("\n")
        content.append("ro.product.brand=").append(brand).append("\n")
        content.append("ro.product.model=").append(model).append("\n")
        content.append("ro.product.device=").append(device).append("\n")
        content.append("ro.product.name=").append(product).append("\n")
        content.append("ro.product.board=").append(board).append("\n")
        content.append("ro.hardware=").append(hardware).append("\n")
        content.append("ro.serialno=").append(serialNumber).append("\n")
        content.append("ro.build.version.release=").append(androidVersion).append("\n")
        content.append("ro.build.type=").append(if (isRoot) "userdebug" else "user").append("\n")
        content.append("ro.build.tags=").append(if (isRoot) "test-keys" else "release-keys").append("\n")
        content.append("ro.debuggable=").append(if (isRoot) "1" else "0").append("\n")
        content.append("ro.secure=").append(if (isRoot) "0" else "1").append("\n")
        content.append("gsm.sim.operator.alpha=").append(carrierName).append("\n")
        content.append("gsm.sim.operator.numeric=").append(mccMnc).append("\n")

        buildPropFile.parentFile?.mkdirs()
        buildPropFile.writeText(content.toString(), Charsets.UTF_8)
    }
}
